package org.kikepb.squadfy.auth

import android.annotation.SuppressLint
import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import com.kikepb.core.domain.auth.model.SignInMethod
import com.kikepb.core.domain.auth.model.SocialCredential
import com.kikepb.core.domain.auth.model.SocialCredentialResult
import com.kikepb.core.domain.auth.repository.SocialCredentialProvider
import com.kikepb.core.domain.logger.SquadfyLogger
import kotlinx.coroutines.CancellationException

/**
 * Google sign-in through Credential Manager's "Sign in with Google" sheet, which always lets the user pick the
 * account (as in TensoScan). Sign in with Apple is not offered on Android: Apple only requires it next to other
 * providers on iOS.
 */
class AndroidSocialCredentialProvider(
    private val context: Context,
    private val logger: SquadfyLogger
) : SocialCredentialProvider {

    override val availableMethods: List<SignInMethod> = listOf(SignInMethod.GOOGLE)

    override suspend fun obtainCredential(method: SignInMethod): SocialCredentialResult {
        if (method != SignInMethod.GOOGLE) return SocialCredentialResult.Unavailable
        val clientId = webClientId() ?: run {
            logger.warn("Google sign-in unavailable: google-services.json has no web client (enable Google in Firebase Auth)")
            return SocialCredentialResult.Unavailable
        }
        val activity = CurrentActivity.activity ?: return SocialCredentialResult.Failed
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(clientId).build())
            .build()
        return try {
            val credential = CredentialManager.create(activity).getCredential(activity, request).credential
            if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                SocialCredentialResult.Success(SocialCredential.Google(GoogleIdTokenCredential.createFrom(credential.data).idToken))
            } else {
                logger.warn("Unexpected credential from Credential Manager: ${credential.type}")
                SocialCredentialResult.Failed
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: GetCredentialCancellationException) {
            SocialCredentialResult.Cancelled
        } catch (e: NoCredentialException) {
            logger.warn("No Google credential available: ${e.message}")
            SocialCredentialResult.Unavailable
        } catch (e: GetCredentialException) {
            logger.error("Google sign-in failed", e)
            SocialCredentialResult.Failed
        } catch (e: GoogleIdTokenParsingException) {
            logger.error("Unreadable Google ID token", e)
            SocialCredentialResult.Failed
        }
    }

    /** Google tokens need no revocation for Firebase: deleting the account is enough. */
    override suspend fun revokeAccess(credential: SocialCredential) = Unit

    /**
     * The OAuth web client of google-services.json, generated by the google-services plugin once Google is enabled in
     * Firebase Auth: looked up by name so the app still builds without it.
     */
    @SuppressLint("DiscouragedApi")
    private fun webClientId(): String? {
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id == 0) null else context.getString(id).takeIf { it.isNotBlank() }
    }
}
